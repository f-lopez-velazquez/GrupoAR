const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const applyCase = (source, target) => {
  if (source.toUpperCase() === source) return target.toUpperCase();
  if (source[0] === source[0].toUpperCase()) {
    return target.charAt(0).toUpperCase() + target.slice(1);
  }
  return target;
};

const translateText = (input) => {
  if (!input || typeof input !== "string") return input;
  let text = input;
  const phraseKeys = Object.keys(phraseMap).sort((a, b) => b.length - a.length);
  phraseKeys.forEach((key) => {
    const regex = new RegExp(escapeRegExp(key), "gi");
    text = text.replace(regex, phraseMap[key]);
  });
  text = text.replace(/\b([A-Za-z][A-Za-z'-]*)\b/g, (match) => {
    const lower = match.toLowerCase();
    if (!wordMap[lower]) return match;
    return applyCase(match, wordMap[lower]);
  });
  return text;
};

const translateNode = (node) => {
  if (!node || node.nodeType !== Node.ELEMENT_NODE) return;

  // Skip script, style, code, pre, AND material icons
  if (node.closest("script, style, code, pre") ||
    node.hasAttribute("data-i18n-skip") ||
    node.classList.contains("material-symbols-outlined") ||
    node.closest(".material-symbols-outlined")) return;

  ["placeholder", "title", "aria-label", "alt", "data-alt"].forEach((attr) => {
    if (node.hasAttribute(attr)) {
      node.setAttribute(attr, translateText(node.getAttribute(attr)));
    }
  });

  node.childNodes.forEach((child) => {
    if (child.nodeType === Node.TEXT_NODE) {
      child.textContent = translateText(child.textContent);
    }
  });
};

const translateDocument = () => {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_ELEMENT, null);
  let current = walker.currentNode;
  while (current) {
    translateNode(current);
    current = walker.nextNode();
  }
};

const observeMutations = () => {
  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.ELEMENT_NODE) {
          translateNode(node);
          node.querySelectorAll("*").forEach((child) => translateNode(child));
        } else if (node.nodeType === Node.TEXT_NODE && node.parentElement) {
          node.textContent = translateText(node.textContent);
        }
      });
    });
  });
  observer.observe(document.body, { childList: true, subtree: true });
};

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", () => {
    translateDocument();
    observeMutations();
  });
} else {
  translateDocument();
  observeMutations();
}
